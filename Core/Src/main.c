/**
* @brief Function implementing the Task_SafetyVoti thread.
* @param argument: Not used
* @retval None
*/
/* USER CODE END Header_Start_Task_SafetyVoting */
/* USER CODE BEGIN Header_Start_Task_SafetyVoting */
/**
* @brief Function implementing the Task_SafetyVoti thread.
* @param argument: Not used
* @retval None
*/
/* USER CODE END Header_Start_Task_SafetyVoting */
void Start_Task_SafetyVoting(void *argument)
{
  /* USER CODE BEGIN Start_Task_SafetyVoting */
  uint16_t adc_sensor_A = 0;
  uint16_t adc_sensor_B = 0;
  uint16_t final_brake_value = 0;

  // Start the PWM Timer native hardware before entering the loop
  HAL_TIM_PWM_Start(&htim1, TIM_CHANNEL_1);

  /* Infinite loop */
  for(;;)
  {
    // 1. Standard Polling Data Acquisition for Sensor A
    HAL_ADC_Start(&hadc1);
    if (HAL_ADC_PollForConversion(&hadc1, 10) == HAL_OK)
    {
        adc_sensor_A = HAL_ADC_GetValue(&hadc1);
    }

    // 2. Standard Polling Data Acquisition for Sensor B
    HAL_ADC_Start(&hadc2);
    if (HAL_ADC_PollForConversion(&hadc2, 10) == HAL_OK)
    {
        adc_sensor_B = HAL_ADC_GetValue(&hadc2);
    }

    // 3. Deadband Check
    if (adc_sensor_A < ADC_DEADBAND && adc_sensor_B < ADC_DEADBAND)
    {
        final_brake_value = 0;
        HAL_GPIO_WritePin(GPIOA, GPIO_PIN_5, GPIO_PIN_SET);   // Green ON
        HAL_GPIO_WritePin(GPIOB, GPIO_PIN_2, GPIO_PIN_RESET); // Red OFF
    }
    // 4. Absolute Difference Check
    else if (abs(adc_sensor_A - adc_sensor_B) > ADC_TOLERANCE)
    {
        final_brake_value = 0; // Force zero output in Safe State
        HAL_GPIO_WritePin(GPIOB, GPIO_PIN_2, GPIO_PIN_SET);   // Red ON (Safe State)
        HAL_GPIO_WritePin(GPIOA, GPIO_PIN_5, GPIO_PIN_RESET); // Green OFF
    }
    // 5. Normal Operation
    else
    {
        final_brake_value = (adc_sensor_A + adc_sensor_B) / 2;
        HAL_GPIO_WritePin(GPIOA, GPIO_PIN_5, GPIO_PIN_SET);   // Green ON
        HAL_GPIO_WritePin(GPIOB, GPIO_PIN_2, GPIO_PIN_RESET); // Red OFF
    }

    // Map the validated 12-bit ADC (0-4095) to the 10-bit PWM (0-1000) for the Blue LED
    uint32_t pwm_duty = (final_brake_value * 1000) / 4095;
    __HAL_TIM_SET_COMPARE(&htim1, TIM_CHANNEL_1, pwm_duty);

    osDelay(10);
  }
  /* USER CODE END Start_Task_SafetyVoting */
}
